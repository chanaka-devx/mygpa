const { chromium } = require('playwright-core');
const fs = require('fs');
(async () => {
  const browser = await chromium.connectOverCDP('http://127.0.0.1:9222', { timeout: 15000 });
  const ctx = browser.contexts()[0];
  const page = ctx.pages().find(p => p.url().includes('sarislabs.com'));
  const client = await ctx.newCDPSession(page);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('https://gpa.sarislabs.com/', { waitUntil: 'networkidle' });
  await page.waitForTimeout(2500);
  console.log('URL after root:', page.url());
  console.log('TITLE:', await page.title());
  const r = await page.evaluate(() => ({ text: document.body.innerText.slice(0, 5000), html: document.body.innerHTML.slice(0, 3000) }));
  console.log(r.text);
  fs.writeFileSync('captures/root-info.json', JSON.stringify(r, null, 2));
  await client.send('Page.bringToFront');
  const s = await client.send('Page.captureScreenshot', { format: 'png', fromSurface: true, captureBeyondViewport: false });
  fs.writeFileSync('captures/root.png', Buffer.from(s.data, 'base64'));
  await browser.close();
})().catch(e => { console.error('ERR', e.message); process.exit(1); });
